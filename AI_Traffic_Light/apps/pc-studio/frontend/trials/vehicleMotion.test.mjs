import assert from 'node:assert/strict';
import {VehicleMotion,mirroredYaw} from '../src/components/vehicleMotion.ts';
const v={id:'v',x:0,y:265,width:140,direction:1,vehicle_type:'car',color:'#e87842'};
const s=(time,vehicles=[v],paused=false,source_id='simulation_camera',density='normal')=>({source_id,simulation_time_seconds:time,paused,density,width:1280,height:720,vehicles});
const m=new VehicleMotion(),near=(a,b)=>assert(Math.abs(a-b)<1e-7, a+' != '+b);
m.update(s(0),0);near(m.pose('v',0).x,70);
m.update(s(.45,[{...v,x:45}]),450);
near(m.pose('v',450).x,70);near(m.pose('v',675).x,92.5);near(m.pose('v',900).x,115);
assert(m.isAnimating(675));assert(!m.isAnimating(900));
m.update(s(.45,[{...v,x:45}]),675);near(m.pose('v',675).x,92.5);
m.update(s(.6,[{...v,x:60}]),750);near(m.pose('v',750).x,100);near(m.pose('v',900).x,130);
m.update(s(.7,[{...v,x:60,y:285}]),900);near(m.pose('v',1000).heading,Math.PI/2);
near(mirroredYaw(0,'simulation_camera'),0);near(Math.abs(mirroredYaw(0,'simulation_camera_c')),Math.PI);
near(mirroredYaw(Math.PI/2,'simulation_camera_b'),Math.PI/2);near(mirroredYaw(Math.PI/2,'simulation_camera_d'),Math.PI/2);
m.update(s(.8,[{...v,x:1401}]),1000);m.update(s(.9,[{...v,x:-250}]),1100);near(m.pose('v',1100).x,-180);assert(!m.isAnimating(1100));
m.update(s(1,[{...v,x:-235}]),1200);near(m.pose('v',1250).x,-172.5);
m.update(s(1.05,[{...v,x:-230}],true),1250);near(m.pose('v',1250).x,-160);assert(!m.isAnimating(1250));
m.update(s(1.05,[{...v,x:-230}],true),9000);near(m.pose('v',9000).x,-160);
m.update(s(1.05,[{...v,x:-230}],false),9100);near(m.pose('v',9100).x,-160);
m.update(s(1.15,[{...v,x:-220}]),9200);near(m.pose('v',9250).x,-155);
m.update(s(0,[{...v,x:100}]),9300);near(m.pose('v',9300).x,170);
m.update(s(.1,[]),9400);assert.equal(m.pose('v',9400),undefined);
m.update(s(.2,[v]),9500);near(m.pose('v',9500).x,70);
m.update(s(.3,[{...v,x:100}],false,'simulation_camera_b'),9600);near(m.pose('v',9600).x,170);
m.update(s(.4,[{...v,x:200}],false,'simulation_camera_b','busy'),9700);near(m.pose('v',9700).x,270);
m.update(null,9800);assert.equal(m.pose('v',9800),undefined);
// Westbound reentry; fixed-time samples are independent of intermediate frame count.
const w={...v,direction:-1,x:1400};m.update(s(0,[w]),0);m.update(s(.4,[{...w,x:1360}]),400);
const mid=m.pose('v',600);for(let t=401;t<600;t+=7)m.pose('v',t);assert.deepEqual(m.pose('v',600),mid);
m.update(s(.5,[{...w,x:-300}]),800);m.update(s(.6,[{...w,x:1450}]),900);near(m.pose('v',900).x,1520);
console.log('[PASS] vehicle motion interpolation, turns/mirrors, reentry both directions, pause/resume, stale/reset/source/density boundaries, disappearance and frame-rate independence');
