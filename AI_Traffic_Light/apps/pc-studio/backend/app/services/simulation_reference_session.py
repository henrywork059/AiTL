"""Interchangeable finite reference session for the protected evaluation owner.

Uses the same generated network, trips and phase-map contract as SUMO.
No libsumo child, no live detector, no production camera or physical output.
The constant-speed reference is NOT the recirculating production legacy world.
"""
from __future__ import annotations

from pathlib import Path
from tempfile import TemporaryDirectory

from app.services.simulation_finite_fixture import FiniteReference, load_trips
from app.services.sumo_shadow_adapter import ShadowAgent, STEP_S
from app.services.sumo_shadow_fixture import PHASES, PhaseMap, generate_controlled_fixture


class ReferenceAgent(ShadowAgent):
    @property
    def id(self):
        return f"reference:{self.kind}:{self.engine_id}"


class FiniteReferenceSession:
    def __init__(self, network: Path, trips, phase_map):
        self.network_path = network
        self.trips = tuple(trips)
        self.phase_map = phase_map
        self._model = FiniteReference(self.trips)
        self._kinds = {t.ident: t.kind for t in self.trips}
        if len(self._kinds) != len(self.trips) or any(
            not t.path or t.path[0].kind.endswith("_gate") or
            (t.kind == "vehicle" and t.path[0].length <= 5.)
            for t in self.trips
        ):
            raise ValueError("Invalid finite reference insertion geometry")
        self._phase = "all_red"
        self._agents = ()
        self.arrived = set()
        self.person_arrived = set()
        self.last_permission = None
        self.closed = False

    def set_phase(self, phase):
        if self.closed or phase not in PHASES:
            raise ValueError("Inactive or invalid reference phase")
        self._phase = phase

    def agents(self):
        if self.closed:
            raise RuntimeError("Reference session closed")
        return self._agents

    def advance(self):
        if self.closed:
            raise RuntimeError("Reference session closed")
        before = self._model.active.copy()
        self.last_permission = self.phase_map.state(self._phase,
            vehicle_inside=any(a.kind == "vehicle" and a.road_id.startswith(":C_") for a in self._agents),
            pedestrian_inside=any(a.kind == "pedestrian" and a.road_id in self.phase_map.crossing_edges for a in self._agents))
        # Permission is generated by the validated phase map, not an arbitrary
        # phase supplied to the world. Existing committed agents may clear.
        phase = self._phase if "G" in self.last_permission else "all_red"
        rows = self._model.advance(phase)
        self._agents = tuple(ReferenceAgent(a.kind, a.engine_id, a.x_m, a.y_m,
            max(0., (self._model.active[a.engine_id][1] -
                (before[a.engine_id][1] if a.engine_id in before else
                    5. if a.kind == "vehicle" else 0.)) / STEP_S), a.road_id)
            for a in rows)
        self.arrived = {i for i in self._model.arrived if self._kinds[i] == "vehicle"}
        self.person_arrived = {i for i in self._model.arrived if self._kinds[i] == "pedestrian"}
        occupied = {t.path[t.locate(pos)[0]].kind for t, pos in self._model.active.values()}
        if {"vehicle_gate", "pedestrian_gate"} <= occupied:
            self.close()
            raise RuntimeError("Conflicting reference gate occupancy")

    def close(self):
        self.closed = True
        self._agents = ()


class GeneratedReferenceSession(FiniteReferenceSession):
    def __init__(self, seed, *, density, geometry="standard"):
        if type(seed) is not int or not 0 <= seed <= 2**31-1:
            raise ValueError("Invalid reference seed")
        self._temp = TemporaryDirectory(prefix="mesh-reference-")
        try:
            root = Path(self._temp.name)
            generate_controlled_fixture(root, density=density, geometry=geometry)
            network = root / "network.xml"
            super().__init__(network, load_trips(network, root / "routes.xml"), PhaseMap.load(network))
        except BaseException:
            self._temp.cleanup()
            raise

    def close(self):
        try:
            super().close()
        finally:
            self._temp.cleanup()
